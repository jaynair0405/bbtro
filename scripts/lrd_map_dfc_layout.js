#!/usr/bin/env node
/**
 * lrd_map_dfc_layout.js
 *
 * Draws the WDFC (PNVL_UDNN route, JNPN .. UDNN) on the LRD SVG map in
 * public/div/ctr-management.html and moves the legend to the bottom right
 * (lobby, 2026-10-23):
 *   - double line, dull amber, stripes 6 apart, ids seg-<from>-<to>-dn (JNPN -> UDNN)
 *     and seg-<from>-<to>-up (UDNN -> JNPN); JNPT-JNPN link stub included;
 *   - starts near JNPT on the upper side of the IR JNPT-PNVL line and runs parallel
 *     to it, crosses the IR chord just before KLMG (an overhead crossing in reality,
 *     drawn over the chord), runs on the lower / right-hand side of the chord up to
 *     BSR, then a new line past BSR to UDNN along the top of the map, with room left
 *     to the right for a later extension to MKPR;
 *   - trains keep left: the JNPN -> UDNN stripe is on the left of its direction of travel.
 * Writes the block between the DFC markers (replacing an earlier block).
 *
 * Usage: node scripts/lrd_map_dfc_layout.js
 */
const fs = require("fs");
process.chdir("/Users/neeraja/bbtro");
const f = "public/div/ctr-management.html";
let html = fs.readFileSync(f, "utf8");

const START = "                        <!-- WDFC: JNPN .. UDNN (generated by scripts/lrd_map_dfc_layout.js) -->";
const END = "                        <!-- /WDFC -->";
const INSERT_BEFORE = "                        <!-- DIVA hub overlay (rendered last to appear on top of lines) -->";

const r1 = (v) => Math.round(v * 10) / 10;
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const add = (a, b) => [a[0] + b[0], a[1] + b[1]];
const mul = (a, k) => [a[0] * k, a[1] * k];
const len = (a) => Math.hypot(a[0], a[1]);
const unit = (a, b) => { const d = sub(b, a), L = len(d); return [d[0] / L, d[1] / L]; };
// left-hand normal of a direction, in screen coordinates (y down): rotate -90deg
const leftOf = (u) => [u[1], -u[0]];

const COLOR = "#a16207";          // dull amber
const GAP = 6;                    // stripe spacing

// ---- centre line of the DFC, following the lobby description
// IR JNPT-PNVL pair centre: JNPT (140,540) .. PNVL (389,459); DFC 17px on its upper side
const JNPT = [140, 540], PNVLb = [389, 459];
const uBranch = unit(JNPT, PNVLb), nUp = leftOf(uBranch);       // up-left of the branch
const OFF = 17;
const A0 = add(JNPT, mul(nUp, OFF));                            // JNPN, beside JNPT
const A1 = add([366, 465], mul(nUp, OFF));                      // end of the parallel run, west of PNVL
// passes the PNVL circle on its west side, climbs beside the chord's UP track, then crosses the
// chord (tracks at x 400 / 406 .. 413) just below KLMG (418) to its right-hand side
const X0 = [383, 440], X1 = [385, 428], X2 = [424, 421];
// up the right-hand side of the chord (dn track x 406..413, DTCC at 406,280)
const C = [[424, 421], [430, 398], [430, 360], [425, 296]];
// lower side of the DTCC .. BSR diagonal (dn track 406,280 -> 318,206 -> 280,190 -> 230,170 -> 180,150 -> 130,130)
const diag = [[406, 280], [318, 206], [280, 190], [230, 170], [180, 150], [130, 130]];
const uD = unit(diag[0], diag[1]), nLow = leftOf(uD);                   // below the diagonal (screen y grows downwards)
const D = diag.map(p => add(p, mul(nLow, OFF)));
// new line past BSR: up the left of BSR, then east along the top
const E = [[112, 125], [100, 95], [100, 48], [160, 40], [620, 40]];

const centre = [A0, A1, X0, X1, X2, ...C.slice(1), ...D.slice(1), ...E];

// stations along the centre line (index into `centre` or explicit points)
const stations = [
  { code: "JNPN", at: A0, label: [-8, -8] },
  { code: "NIJN", at: [430, 340], label: [10, 3] },
  { code: "KHBN", at: D[3], label: [-30, 14] },
  { code: "SAHN", at: [100, 70], label: [-36, 3] },
  { code: "PLGR", at: [230, 40], label: [-14, -7] },
  { code: "UBRN", at: [300, 40], label: [-14, -7] },
  { code: "AFAS", at: [370, 40], label: [-14, -7] },
  { code: "PADN", at: [440, 40], label: [-14, -7] },
  { code: "ACLN", at: [510, 40], label: [-14, -7] },
  { code: "BHEN", at: [570, 40], label: [-14, -7] },
  { code: "UDNN", at: [620, 40], label: [10, 4], hub: true },
];
const order = ["JNPN", "NIJN", "KHBN", "SAHN", "PLGR", "UBRN", "AFAS", "PADN", "ACLN", "BHEN", "UDNN"];

// ---- walk the centre line; split it at the station points (projected onto the polyline)
function project(p) {
  let best = null;
  for (let i = 0; i < centre.length - 1; i++) {
    const a = centre[i], b = centre[i + 1], ab = sub(b, a), L2 = ab[0] * ab[0] + ab[1] * ab[1];
    let t = ((p[0] - a[0]) * ab[0] + (p[1] - a[1]) * ab[1]) / L2; t = Math.max(0, Math.min(1, t));
    const q = add(a, mul(ab, t)), d = len(sub(p, q));
    if (!best || d < best.d) best = { d, i, t, q };
  }
  return best;
}
const marks = stations.map(s => ({ ...s, ...project(s.at) }));
// polyline between two marks
function piece(m1, m2) {
  const raw = [m1.q];
  for (let i = m1.i + 1; i <= m2.i; i++) raw.push(centre[i]);
  raw.push(m2.q);
  // a station projected onto a vertex repeats that vertex: drop zero-length steps
  return raw.filter((p, i) => i === 0 || len(sub(p, raw[i - 1])) > 0.01);
}
// offset a polyline to one side by k px (mitre-less: per-point normal of the following segment)
function offsetLine(pts, side, k) {
  return pts.map((p, i) => {
    const u = i < pts.length - 1 ? unit(pts[i], pts[i + 1]) : unit(pts[i - 1], pts[i]);
    const n = leftOf(u);
    return add(p, mul(n, side * k));
  });
}
const d = (pts) => "M" + pts.map(p => `${r1(p[0])} ${r1(p[1])}`).join(" L");
const path = (id, pts) => `<path id="${id}" d="${d(pts)}" data-base="${COLOR}" stroke="${COLOR}" stroke-width="3" fill="none"/>`;

const ind = "                            ";
const out = [START, `                        <g id="route-dfc" class="route-group">`];
out.push(ind + `<!-- JNPT - JNPN link (6.6 km), a stub between the two terminals -->`);
const jnpt = [135, 540], jnpn = marks[0].q;
const uL = unit(jnpt, jnpn), nL = leftOf(uL);
out.push(ind + path("seg-jnpt-jnpn-dn", [add(jnpt, mul(nL, GAP / 2)), add(jnpn, mul(nL, GAP / 2))]));
out.push(ind + path("seg-jnpn-jnpt-up", [add(jnpn, mul(nL, -GAP / 2)), add(jnpt, mul(nL, -GAP / 2))]));
for (let i = 0; i < order.length - 1; i++) {
  const m1 = marks.find(m => m.code === order[i]), m2 = marks.find(m => m.code === order[i + 1]);
  const pts = piece(m1, m2);
  // JNPN -> UDNN travels along `pts`; keep left => offset to the left of travel
  out.push(ind + path(`seg-${order[i].toLowerCase()}-${order[i + 1].toLowerCase()}-dn`, offsetLine(pts, +1, GAP / 2)));
  out.push(ind + path(`seg-${order[i + 1].toLowerCase()}-${order[i].toLowerCase()}-up`, offsetLine(pts, -1, GAP / 2).reverse()));
}
for (const m of marks) {
  if (m.hub) {
    out.push(ind + `<circle cx="${r1(m.q[0])}" cy="${r1(m.q[1])}" r="7" fill="${COLOR}" stroke="#78350f" stroke-width="2"/>`);
    out.push(ind + `<text x="${r1(m.q[0] + m.label[0])}" y="${r1(m.q[1] + m.label[1])}" font-size="10" font-weight="600" fill="${COLOR}">${m.code}</text>`);
  } else {
    out.push(ind + `<circle cx="${r1(m.q[0])}" cy="${r1(m.q[1])}" r="3" fill="${COLOR}" stroke="#78350f" stroke-width="1"/>`);
    out.push(ind + `<text x="${r1(m.q[0] + m.label[0])}" y="${r1(m.q[1] + m.label[1])}" font-size="7" fill="#d6a85c">${m.code}</text>`);
  }
}
out.push(ind + `<text x="700" y="44" font-size="7" fill="#6b7a99">(to MKPR)</text>`);
out.push(`                        </g>`, END);
const block = out.join("\n") + "\n";

// ---- splice
const s = html.indexOf(START), e = html.indexOf(END);
if (s >= 0 && e > s) {
  html = html.slice(0, s) + block + html.slice(e + END.length + 1);
} else {
  const at = html.indexOf(INSERT_BEFORE);
  if (at < 0) throw new Error("insertion marker not found");
  html = html.slice(0, at) + block + html.slice(at);
}

// ---- legend to the bottom right, with a DFC entry
html = html.replace(/<g transform="translate\(10, 10\)">\n(\s*)<rect x="0" y="0" width="200" height="70"/, (m, sp) => `<g transform="translate(790, 620)">\n${sp}<rect x="0" y="0" width="200" height="70"`);
if (!html.includes('>DFC</text>')) {
  html = html.replace(/(<text x="35" y="56" font-size="10" fill="#eaf0ff">Never Worked<\/text>)/,
    `$1\n                            <line x1="140" y1="52" x2="160" y2="52" stroke="${COLOR}" stroke-width="4"/><text x="165" y="56" font-size="10" fill="#eaf0ff">DFC</text>`);
}
fs.writeFileSync(f, html);
const ids = [...block.matchAll(/id="(seg-[^"]+)"/g)].map(m => m[1]);
console.log("DFC block written:", ids.length, "paths;", stations.length, "stations; legend at bottom right");
