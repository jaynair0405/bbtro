-- ---- backups: IF NOT EXISTS so a re-run cannot overwrite good pre-change rows
CREATE TABLE IF NOT EXISTS bak_20260902_motnom_nominations AS
SELECT n.* FROM div_cli_nominations n
WHERE n.staff_hrms_id IN (SELECT staff_hrms_id FROM stg_motnom_28aug);

CREATE TABLE IF NOT EXISTS bak_20260902_motnom_staff AS
SELECT hrms_id, name, current_cli_id, current_office_code, designation_id
FROM div_staff_master WHERE hrms_id IN (SELECT staff_hrms_id FROM stg_motnom_28aug);

CREATE TABLE IF NOT EXISTS bak_20260902_patwekar_office AS
SELECT cli_id, cli_name, cmsid, current_office_code FROM div_cli_master WHERE cmsid = 'CSTM0060';

-- ---- pre-checks: refuse to proceed on a surprise ---------------------------
SELECT 'staging rows'                        AS check_name, COUNT(*) AS n FROM stg_motnom_28aug
UNION ALL SELECT 'staff not found on this database (must be 0)', COUNT(*)
  FROM stg_motnom_28aug s LEFT JOIN div_staff_master m ON m.hrms_id = s.staff_hrms_id
 WHERE m.hrms_id IS NULL
UNION ALL SELECT 'target CLI not found or inactive (must be 0)', COUNT(*)
  FROM stg_motnom_28aug s LEFT JOIN div_cli_master c
    ON c.cmsid = s.new_cli_cmsid AND c.is_active = 1
 WHERE c.cli_id IS NULL
UNION ALL SELECT 'already nominated to the right CLI (will be skipped)', COUNT(*)
  FROM stg_motnom_28aug s
  JOIN div_staff_master m ON m.hrms_id = s.staff_hrms_id
  JOIN div_cli_master  c ON c.cmsid    = s.new_cli_cmsid
 WHERE m.current_cli_id = c.cli_id
UNION ALL SELECT 'will actually move', COUNT(*)
  FROM stg_motnom_28aug s
  JOIN div_staff_master m ON m.hrms_id = s.staff_hrms_id
  JOIN div_cli_master  c ON c.cmsid    = s.new_cli_cmsid
 WHERE m.current_cli_id IS NULL OR m.current_cli_id <> c.cli_id;

-- ---- the writes, atomically ------------------------------------------------
START TRANSACTION;

-- 1. R I PATWEKAR to the suburban lobby his motormen sit in.
UPDATE div_cli_master SET current_office_code = 'PNVL-SUB'
 WHERE cmsid = 'CSTM0060' AND current_office_code = 'PNVL-ML';

-- 2. Expire the outgoing nomination, with a to-date so it can be restored.
UPDATE div_cli_nominations n
  JOIN stg_motnom_28aug s ON s.staff_hrms_id = n.staff_hrms_id
  JOIN div_cli_master   c ON c.cmsid = s.new_cli_cmsid
   SET n.status = 'Expired',
       n.nominated_to_date = CURDATE(),
       n.updated_by = 'motnom-28aug',
       n.updated_at = NOW()
 WHERE n.status = 'Active' AND n.cli_id <> c.cli_id;

-- 3. Nominate to the CLI named in the sheet -- but ONLY where the staff member
--    is not already actively nominated to that CLI.
--
--    The NOT EXISTS is load-bearing. uniq_cli_nomination is
--    (staff_hrms_id, cli_id, nominated_from_date), so ON DUPLICATE KEY alone
--    does NOT catch someone already nominated to this same CLI on an EARLIER
--    date -- it would insert a second row and leave them with two Active
--    nominations. A scratch run of this file produced 384 such duplicates
--    before this guard was added. Most of the sheet confirms nominations that
--    already exist, so this is the common case, not the edge case.
INSERT INTO div_cli_nominations
    (staff_hrms_id, cli_id, nominated_from_date, status, remarks, created_by, created_at)
SELECT s.staff_hrms_id, c.cli_id, CURDATE(), 'Active',
       CONCAT('Motorman nomination list 28-08-2026, sr ', s.sheet_sr),
       'motnom-28aug', NOW()
  FROM stg_motnom_28aug s
  JOIN div_cli_master c ON c.cmsid = s.new_cli_cmsid
 WHERE NOT EXISTS (
       SELECT 1 FROM div_cli_nominations n
        WHERE n.staff_hrms_id = s.staff_hrms_id
          AND n.cli_id = c.cli_id
          AND n.status = 'Active')
ON DUPLICATE KEY UPDATE
    status = 'Active', nominated_to_date = NULL,
    updated_by = 'motnom-28aug', updated_at = NOW();

-- 4. Keep the denormalised pointer in step, exactly as cliRoutes.js does.
UPDATE div_staff_master m
  JOIN stg_motnom_28aug s ON s.staff_hrms_id = m.hrms_id
  JOIN div_cli_master   c ON c.cmsid = s.new_cli_cmsid
   SET m.current_cli_id = c.cli_id;

COMMIT;

