-- 0. Backup existing 8->7 rows (plain CREATE: 2nd run errors here & stops)
CREATE TABLE div_promotion_history_bak_20260722_lpm AS
SELECT p.*
FROM div_promotion_history p
JOIN _promo_stage g ON g.hrms_id = p.staff_hrms_id
WHERE p.from_designation_id = 8 AND p.to_designation_id = 7;

-- 1. Dedup: keep lowest promotion_id per staff for 8->7
DELETE p FROM div_promotion_history p
JOIN _promo_stage g ON g.hrms_id = p.staff_hrms_id
JOIN (
  SELECT staff_hrms_id, MIN(promotion_id) AS keep_id
  FROM div_promotion_history
  WHERE from_designation_id = 8 AND to_designation_id = 7
  GROUP BY staff_hrms_id HAVING COUNT(*) > 1
) d ON d.staff_hrms_id = p.staff_hrms_id AND p.promotion_id <> d.keep_id
WHERE p.from_designation_id = 8 AND p.to_designation_id = 7;

-- 2. UPDATE existing 8->7 rows to the authoritative CSV date
UPDATE div_promotion_history p
JOIN _promo_stage g ON g.hrms_id = p.staff_hrms_id
SET p.posting_date = g.posting_date
WHERE p.from_designation_id = 8 AND p.to_designation_id = 7
  AND p.posting_date <> g.posting_date;

-- 3. INSERT staff with no 8->7 row yet (skips existing, FK-safe)
INSERT INTO div_promotion_history
  (staff_hrms_id, from_designation_id, to_designation_id, change_type,
   posting_date, created_by)
SELECT g.hrms_id, 8, 7, 'Promotion', g.posting_date, 'promotion_import_2026'
FROM _promo_stage g
JOIN div_staff_master s ON s.hrms_id = g.hrms_id
WHERE NOT EXISTS (
  SELECT 1 FROM div_promotion_history p
  WHERE p.staff_hrms_id = g.hrms_id
    AND p.from_designation_id = 8 AND p.to_designation_id = 7
);

DROP TEMPORARY TABLE _promo_stage;
